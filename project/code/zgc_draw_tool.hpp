#ifndef __zgc_draw_tool_HPP__
#define __zgc_draw_tool_HPP__

#include "image_size.hpp"
#include "zf_common_typedef.hpp"

// =====================================================================================================================
// 本库所有绘图函数的颜色参数 color 均为 RGB565 格式的 uint16 值，与上位机 SCC8660 彩色图传兼容。
//
// 逐飞库内置颜色（zf_common_font.hpp rgb565_color_enum），可直接使用：
//   RGB565_RED      (0xF800) — 红色
//   RGB565_GREEN    (0x07E0) — 绿色
//   RGB565_BLUE     (0x001F) — 蓝色
//   RGB565_YELLOW   (0xFFE0) — 黄色
//   RGB565_CYAN     (0x07FF) — 青色
//   RGB565_MAGENTA  (0xF81F) — 品红
//   RGB565_PURPLE   (0xF81F) — 紫色
//   RGB565_PINK     (0xFE19) — 粉色
//   RGB565_BROWN    (0xBC40) — 棕色
//   RGB565_GRAY     (0x8430) — 灰色
//   RGB565_WHITE    (0xFFFF) — 白色
//   RGB565_BLACK    (0x0000) — 黑色
//
// 调试建议配色：
//   搜线起始点      → 绿色/蓝色十字
//   左边界搜线轨迹  → 红色点迹
//   右边界搜线轨迹  → 蓝色点迹
//   拐点候选框      → 黄色空心框
//   圆环元素区域    → 青色空心圆
//   十字元素区域    → 品红标记
// =====================================================================================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     画点函数
// 参数说明     img             目标 RGB565 图像数组指针 尺寸 [image_height][image_width]
// 参数说明     x               坐标x方向 [0, image_width-1]
// 参数说明     y               坐标y方向 [0, image_height-1]
// 参数说明     color           RGB565 颜色值，见文件头说明
// 返回参数     void
// 使用示例     dbg_point(debug_image, 80, 60, RGB565_RED);
// 备注信息     坐标越界自动跳过；所有上层绘图函数最终都通过本函数落点
//-------------------------------------------------------------------------------------------------------------------
void dbg_point(uint16 (*img)[image_width], int x, int y, uint16 color);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     十字标记
// 参数说明     img             目标 RGB565 图像数组指针
// 参数说明     x               十字中心x坐标 [0, image_width-1]
// 参数说明     y               十字中心y坐标 [0, image_height-1]
// 参数说明     color           RGB565 颜色值，见文件头说明
// 参数说明     half            十字臂半长（像素），half=2 则十字总长5像素
// 返回参数     void
// 使用示例     dbg_cross(debug_image, start_point_l[0], start_point_l[1], RGB565_GREEN, 2);
// 备注信息     适合标记搜线起始点、拐点等关键坐标
//-------------------------------------------------------------------------------------------------------------------
void dbg_cross(uint16 (*img)[image_width], int x, int y, uint16 color, int half);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     空心正方形框
// 参数说明     img             目标 RGB565 图像数组指针
// 参数说明     x               框中心x坐标 [0, image_width-1]
// 参数说明     y               框中心y坐标 [0, image_height-1]
// 参数说明     half            框半边长（像素），half=3 则外框为 7x7
// 参数说明     color           RGB565 颜色值，见文件头说明
// 返回参数     void
// 使用示例     dbg_rect(debug_image, corner_x, corner_y, 3, RGB565_YELLOW);
// 备注信息     适合框选拐点、候选元素区域，只描边框不填充内部
//-------------------------------------------------------------------------------------------------------------------
void dbg_rect(uint16 (*img)[image_width], int x, int y, int half, uint16 color);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     实心矩形填充
// 参数说明     img             目标 RGB565 图像数组指针
// 参数说明     x1              矩形左上角x坐标
// 参数说明     y1              矩形左上角y坐标
// 参数说明     x2              矩形右下角x坐标
// 参数说明     y2              矩形右下角y坐标
// 参数说明     color           RGB565 颜色值，见文件头说明
// 返回参数     void
// 使用示例     dbg_fill_rect(debug_image, 10, 20, 30, 40, RGB565_BLUE);
// 备注信息     x1/x2、y1/y2 无需保证大小顺序，内部自动交换并裁剪到有效范围
//-------------------------------------------------------------------------------------------------------------------
void dbg_fill_rect(uint16 (*img)[image_width], int x1, int y1, int x2, int y2, uint16 color);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     Bresenham 直线
// 参数说明     img             目标 RGB565 图像数组指针
// 参数说明     x1              线段起点x坐标 [0, image_width-1]
// 参数说明     y1              线段起点y坐标 [0, image_height-1]
// 参数说明     x2              线段终点x坐标 [0, image_width-1]
// 参数说明     y2              线段终点y坐标 [0, image_height-1]
// 参数说明     color           RGB565 颜色值，见文件头说明
// 返回参数     void
// 使用示例     dbg_line(debug_image, 0, 60, 159, 60, RGB565_GREEN);
// 备注信息     纯整数 Bresenham 算法，无浮点、无除法；单点越界自动跳过
//-------------------------------------------------------------------------------------------------------------------
void dbg_line(uint16 (*img)[image_width], int x1, int y1, int x2, int y2, uint16 color);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     空心圆
// 参数说明     img             目标 RGB565 图像数组指针
// 参数说明     cx              圆心x坐标 [0, image_width-1]
// 参数说明     cy              圆心y坐标 [0, image_height-1]
// 参数说明     r               半径（像素），r<=0 时不绘制
// 参数说明     color           RGB565 颜色值，见文件头说明
// 返回参数     void
// 使用示例     dbg_circle(debug_image, 80, 60, 10, RGB565_CYAN);
// 备注信息     Bresenham 中点画圆算法，纯整数运算；适合标注圆环元素搜圈区域
//-------------------------------------------------------------------------------------------------------------------
void dbg_circle(uint16 (*img)[image_width], int cx, int cy, int r, uint16 color);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示单个 6x8 ASCII 字符
// 参数说明     img             目标 RGB565 图像数组指针
// 参数说明     x               字符左上角 x 坐标
// 参数说明     y               字符左上角 y 坐标
// 参数说明     ch              ASCII 字符，超出可显示范围时自动替换为 '?'
// 参数说明     color           前景色
// 参数说明     bg_color        背景色
// 参数说明     transparent_bg  true=背景透明，仅绘制前景；false=前景/背景都写入
// 返回参数     void
// 使用示例     dbg_char_6x8(debug_image, 2, 2, 'A', RGB565_WHITE, RGB565_BLACK, false);
//-------------------------------------------------------------------------------------------------------------------
void dbg_char_6x8(uint16 (*img)[image_width], int x, int y, char ch,
                  uint16 color, uint16 bg_color, bool transparent_bg = false);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示 6x8 ASCII 字符串，支持 '\n' 换行
// 参数说明     img             目标 RGB565 图像数组指针
// 参数说明     x               字符串左上角 x 坐标
// 参数说明     y               字符串左上角 y 坐标
// 参数说明     text            以 '\0' 结尾的 ASCII 字符串
// 参数说明     color           前景色
// 参数说明     bg_color        背景色
// 参数说明     transparent_bg  true=背景透明，仅绘制前景；false=前景/背景都写入
// 返回参数     void
// 使用示例     dbg_text_6x8(debug_image, 2, 2, "CIPM>20", RGB565_WHITE, RGB565_BLACK, false);
//-------------------------------------------------------------------------------------------------------------------
void dbg_text_6x8(uint16 (*img)[image_width], int x, int y, const char *text,
                  uint16 color, uint16 bg_color, bool transparent_bg = false);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     离散点轨迹描点
// 参数说明     img             目标 RGB565 图像数组指针
// 参数说明     points          点坐标数组，每个元素为 {x, y}
// 参数说明     count           数组中有效点的个数
// 参数说明     color           RGB565 颜色值，见文件头说明
// 参数说明     step            采样间隔，step=1 描所有点，step=2 每隔一个描一个
// 返回参数     void
// 使用示例     dbg_trace_points(debug_image, points_l, g_left_point_count, RGB565_RED, 3);
// 备注信息     适合可视化八邻域搜线路径、离散边界点集；越界点自动跳过
//-------------------------------------------------------------------------------------------------------------------
void dbg_trace_points(uint16 (*img)[image_width],
                      const uint16 points[][2], uint16 count,
                      uint16 color, int step);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     灰度图转 RGB565 图像，感知逆透视有效区
// 参数说明     dst             目标 RGB565 图像数组指针 尺寸 [image_height][image_width]
// 参数说明     src             源灰度图像数组指针 尺寸 [image_height][image_width]，0=黑 255=白
// 参数说明     valid_l         每行有效区左边界数组，传 nullptr 表示整行有效
// 参数说明     valid_r         每行有效区右边界数组，传 nullptr 表示整行有效
// 参数说明     invalid_color   无效区填充颜色（RGB565）
// 参数说明     big_endian      true 时产出大端序 RGB565（逐飞 SCC8660 图传链路专用），默认 false
// 返回参数     void
// 使用示例     dbg_from_gray(debug_image, bin_image, valid_l_bound, valid_r_bound, 0x000F, true);
// 备注信息     有效区内灰度→RGB565 转换；无效区用 invalid_color 填充；必须先调用再叠加其他调试标记
//-------------------------------------------------------------------------------------------------------------------
void dbg_from_gray(uint16 (*dst)[image_width],
                   const uint8 (*src)[image_width],
                   const int *valid_l, const int *valid_r,
                   uint16 invalid_color, bool big_endian = false);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     帧率测量计时起点，在 Image_Process 或 image_test 入口处调用
//-------------------------------------------------------------------------------------------------------------------
void fps_timer_start(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     帧率测量计时终点，在 Image_Process 或 image_test 出口处调用
// 备注信息     每帧更新 g_frame_time_ms；每秒更新一次 g_fps_value
//-------------------------------------------------------------------------------------------------------------------
void fps_timer_end(void);

//-------------------------------------------------------------------------------------------------------------------
// 全局变量     g_fps_value     平滑帧率（fps），每秒更新一次，初始 0
//              g_frame_time_ms 最近一帧图像处理耗时（毫秒），每帧更新
// 使用示例     dbg_text_6x8(img, 2, 2, buf, ...);  // 将 g_fps_value 绘到调试图上
//-------------------------------------------------------------------------------------------------------------------
extern float g_fps_value;// 平滑后的帧率，每秒更新一次
extern float g_frame_time_ms;// 最近一帧图像处理耗时（毫秒），每帧更新

#endif
